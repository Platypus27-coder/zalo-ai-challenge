"""Part B — Text Normalizer: NFC normalization with ID preservation and Slot protection.

Rules:
- NFC normalize Vietnamese text (diacritics consistency)
- Restore leading zero on phone numbers (03x, 05x, 07x, 08x, 09x)
- Preserve opaque IDs returned from tool results (don't NFC those)
- Collapse whitespace
- Preserve negation, numbers, time, phone numbers exactly
- Don't transform ambiguous sentences into certain requests
"""
import re
import unicodedata


def normalize_nfc(text: str) -> str:
    """Apply Unicode NFC normalization to text."""
    if not isinstance(text, str):
        return str(text)
    return unicodedata.normalize("NFC", text)


def normalize_whitespace(text: str) -> str:
    """Collapse multiple whitespace into single space, strip."""
    return " ".join(text.split())


# === Phonetic Dictionary Fixes & Hallucination Stripper ===

PHONETIC_FIXES = {
    # Brand & Tech names misheard by Whisper Vietnamese tokenizer
    r'\b(?:dạ|già|giao)\s*lô\b': 'Zalo',
    r'\bvề\s*ô\s*viên\b': 'VOV',
    r'\btrích\s*áo\b': 'check-out',
    r'\bcơm\s*8[aA]\b': 'cơm tấm',
    # Regional & colloquial negation words normalized to standard
    r'\bhổng\s*có\b': 'không có',
    r'\bchả\s': 'chẳng ',
}

HALLUCINATION_PATTERNS = [
    r'hãy\s+like\s+và\s+sub(?:scribe)?\b.*',
    r'đăng\s+ký\s+kênh\b.*',
    r'cảm\s+ơn\s+các\s+bạn\s+đã\s+(?:theo\s+dõi|xem)\b.*',
    r'nhớ\s+bấm\s+chuông\b.*',
    r'xem\s+thêm\s+tại\b.*',
    r'chúc\s+các\s+bạn\s+(?:vui\s+vẻ|một\s+ngày\s+tốt\s+lành)\b.*',
]


def strip_hallucinations(text: str) -> str:
    """Strip common social media subtitle hallucinations generated by Whisper during silence."""
    if not text:
        return ""
    for pat in HALLUCINATION_PATTERNS:
        text = re.sub(pat, '', text, flags=re.IGNORECASE)
    return text.strip()


def apply_phonetic_fixes(text: str) -> str:
    """Apply targeted phonetic corrections for Vietnamese speech."""
    if not text:
        return ""
    for pattern, replacement in PHONETIC_FIXES.items():
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    return text


def fix_phone_leading_zero(text: str) -> str:
    """Restore missing leading zero for Vietnamese phone numbers.
    
    Whisper often transcribes '0912345678' as '912345678' or '912 345 678'.
    Vietnamese mobile numbers are 10 digits starting with:
    03x, 05x, 07x, 08x, 09x.
    
    SAFETY GUARDS:
    1. Do NOT block 'chuyển' / 'tiền' prefix (users say 'chuyển cho 912345678').
    2. Block if followed by currency units (đồng, đ, vnd, k, triệu...).
    3. Block if ends with >= 5 trailing zeros (300000000 = 300 million amount).
    4. Block if strictly preceded by transaction / ID / account number prefix.
    """
    if not text:
        return ""

    ID_PREFIX_PATTERN = r'(?:mã\s*(?:giao\s*dịch|đơn|xác\s*nhận|pin|otp)?|code|id|stk|số\s*(?:tài\s*khoản|cccd|cmnd))\s*[:=]?\s*$'
    MONEY_SUFFIX_PATTERN = r'^\s*(?:đồng|đ|vnd|vnđ|nghìn|ngàn|triệu|k|tr)\b'

    def _should_fix(match):
        digits = match.group(1)

        # 1. Block round amounts like 300000000, 500000000 (>= 5 trailing zeros)
        trailing_zeros = len(digits) - len(digits.rstrip('0'))
        if trailing_zeros >= 5:
            return digits

        # 2. Check suffix for currency units
        end_pos = match.end()
        suffix = text[end_pos:end_pos + 15].lower()
        if re.search(MONEY_SUFFIX_PATTERN, suffix, re.IGNORECASE):
            return digits

        # 3. Check prefix for ID / account number labels
        start_pos = max(0, match.start() - 25)
        prefix = text[start_pos:match.start()].lower()
        if re.search(ID_PREFIX_PATTERN, prefix, re.IGNORECASE):
            return digits

        return "0" + digits

    # Pattern 1: Contiguous 9 digits starting with 3, 5, 7, 8, 9
    text = re.sub(r'(?<!\d)([35789]\d{8})(?!\d)', _should_fix, text)

    # Pattern 2: Spaced format like "912 345 678" or "91 234 5678"
    def _fix_spaced_phone(match):
        raw = match.group(0)
        digits = re.sub(r'\D', '', raw)
        if len(digits) == 9 and digits[0] in "35789":
            end_pos = match.end()
            suffix = text[end_pos:end_pos + 15].lower()
            if re.search(MONEY_SUFFIX_PATTERN, suffix, re.IGNORECASE):
                return raw
            return "0" + raw
        return raw

    text = re.sub(
        r'(?<!\d)([35789]\d{1,3}[\s.-]\d{2,4}[\s.-]\d{3,4})(?!\d)',
        _fix_spaced_phone,
        text
    )

    return text


def normalize_transcript(text: str) -> str:
    """Full normalization pipeline for ASR transcript output.
    
    Steps:
    1. NFC normalization (Vietnamese diacritics)
    2. Phonetic corrections (Zalo, VOV, check-out...)
    3. Hallucination stripping (YouTube subtitle artifacts)
    4. Leading zero restoration for phone numbers (with money guards)
    5. Whitespace collapse & trim
    
    Preserves:
    - Negation words (không, đừng, chưa, hủy, etc.)
    - Numbers, amounts, and dates
    - Proper nouns and entity names
    """
    if not text:
        return ""
    
    text = normalize_nfc(text)
    text = apply_phonetic_fixes(text)
    text = strip_hallucinations(text)
    text = fix_phone_leading_zero(text)
    text = normalize_whitespace(text)
    
    return text.strip()


def normalize_for_fuzzy(text: str) -> str:
    """Normalize text specifically for fuzzy matching evaluation.
    
    Following evaluator rules:
    - NFC normalization
    - Lowercase
    """
    if not isinstance(text, str):
        return str(text).lower()
    return unicodedata.normalize("NFC", text).lower()


# === Negation Words & Slot Protection ===

NEGATION_WORDS = {
    "không", "đừng", "chưa", "hủy", "thôi", "ngưng",
    "bỏ", "tắt", "dừng", "chẳng", "khỏi", "hổng", "chả", "chớ"
}

def verify_negation_preserved(gold: str, pred: str) -> dict:
    """Check if negation words are preserved between gold and pred.
    Used in benchmarking and quality assurance.
    """
    gold_negs = {w for w in gold.lower().split() if w in NEGATION_WORDS}
    pred_negs = {w for w in pred.lower().split() if w in NEGATION_WORDS}
    return {
        "gold_negations": list(gold_negs),
        "pred_negations": list(pred_negs),
        "match": gold_negs == pred_negs,
        "missing": list(gold_negs - pred_negs),
        "extra": list(pred_negs - gold_negs),
    }


# === Number & Entity Extraction Helpers ===

_VN_DIGITS = {
    "không": "0", "một": "1", "hai": "2", "ba": "3", "bốn": "4",
    "năm": "5", "sáu": "6", "bảy": "7", "tám": "8", "chín": "9",
    "mười": "10", "mươi": "0",
}

_VN_MULTIPLIERS = {
    "nghìn": 1000, "ngàn": 1000,
    "triệu": 1_000_000,
    "tỷ": 1_000_000_000,
    "trăm": 100,
}

_COMMON_CORRECTIONS = {
    "book": "book",
    "booking": "booking",
    "cancel": "cancel",
    "AC": "AC",
    "air con": "AC",
    "wifi": "wifi",
    "OK": "OK",
}


def extract_phone_number(text: str) -> list[str]:
    """Extract Vietnamese phone numbers from text."""
    patterns = [
        r'0\d{2}[\s.-]?\d{3}[\s.-]?\d{4}',
        r'0\d{9}',
        r'\+84\d{9,10}',
    ]
    numbers = []
    for pattern in patterns:
        matches = re.findall(pattern, text)
        numbers.extend(matches)
    return numbers


def extract_money_amount(text: str) -> list[dict]:
    """Extract money amounts from Vietnamese text.
    Handles: 50 nghìn, 500k, 1 triệu, 1.5 triệu, etc.
    """
    results = []
    patterns = [
        (r'(\d+(?:[.,]\d+)?)\s*(nghìn|ngàn|triệu|tỷ|trăm)', None),
        (r'(\d+(?:[.,]\d+)?)\s*[kK]', 1000),
        (r'(\d+(?:[.,]\d+)?)\s*tr', 1_000_000),
        (r'(\d{4,})', 1),
    ]
    for pattern, fixed_mult in patterns:
        for match in re.finditer(pattern, text):
            num_str = match.group(1).replace(",", ".")
            try:
                num = float(num_str)
                if fixed_mult:
                    amount = int(num * fixed_mult)
                else:
                    unit = match.group(2).lower()
                    mult = _VN_MULTIPLIERS.get(unit, 1)
                    amount = int(num * mult)
                results.append({"text": match.group(0), "amount": amount})
            except (ValueError, IndexError):
                pass
    return results


def extract_time_expressions(text: str, current_time: str | None = None) -> list[str]:
    """Extract time-related expressions from Vietnamese text."""
    time_patterns = [
        r'\d{1,2}\s*(?:giờ|h)\s*(?:\d{1,2}\s*(?:phút|p))?',
        r'\d{1,2}:\d{2}',
        r'(?:sáng|trưa|chiều|tối|đêm)\s*(?:nay|mai)?',
        r'(?:ngày\s*)?mai',
        r'hôm\s*(?:nay|qua)',
        r'(?:thứ|chủ\s*nhật)\s*\d?',
        r'tuần\s*(?:này|sau|trước)',
        r'tháng\s*\d{1,2}',
        r'ngày\s*\d{1,2}(?:/\d{1,2})?',
    ]
    results = []
    for pattern in time_patterns:
        matches = re.findall(pattern, text, re.IGNORECASE)
        results.extend(matches)
    return results


